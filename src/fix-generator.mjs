/**
 * Auto-Fix Pack Generator: creates 6 ready-to-deploy files from crawled site data.
 */

import { escapeHtml } from './html-parser.mjs';
import { validateLlmsTxt } from './llmstxt-validator.mjs';
import { parseRobotsTxt } from './robots-parser.mjs';

function inferBrandName(parsed, origin) {
  const ogSite = parsed.metaMap['og:site_name'];
  if (ogSite && ogSite.length <= 48) return ogSite.trim();

  if (parsed.title) {
    const split = parsed.title.split(/\s*[|–—:-]\s*/)[0].trim();
    if (split && split.length >= 2 && split.length <= 42) return split;
  }

  try {
    const host = new URL(origin).hostname.replace(/^www\./, '');
    const core = host.split('.')[0];
    return core.charAt(0).toUpperCase() + core.slice(1);
  } catch {
    return 'Your Brand';
  }
}

function inferSummary(parsed, brandName) {
  const desc = parsed.metaMap.description || parsed.metaMap['og:description'] || '';
  if (desc && desc.length >= 25) return desc.trim();
  if (parsed.firstParagraph && parsed.firstParagraph.length >= 25) {
    return parsed.firstParagraph.slice(0, 200).trim();
  }
  return `${brandName} provides software and documentation accessible at ${parsed.canonical || 'its official website'}.`;
}

function safeJsonLdScript(obj) {
  const json = JSON.stringify(obj, null, 2).replace(/</g, '\\u003c');
  JSON.parse(json); // invariant verification
  return `<script type="application/ld+json">\n${json}\n</script>`;
}

function buildLlmsTxt(siteData, brandName, summary) {
  const origin = siteData.origin;
  const home = siteData.pages[0];
  const pages = siteData.pages.filter((p) => p.ok || p.path === '/');

  const coreLinks = [];
  const optionalLinks = [];
  const seen = new Set();

  for (const p of pages) {
    if (seen.has(p.url)) continue;
    seen.add(p.url);
    const label = p.parsed.title || (p.path === '/' ? `${brandName} Home` : p.path);
    const note =
      p.parsed.metaMap.description ||
      p.parsed.firstParagraph?.slice(0, 110) ||
      `Primary resource at ${p.path}`;
    const line = `- [${label}](${p.url}): ${note.replace(/\s+/g, ' ').trim()}`;
    if (/privacy|terms|legal|cookie|changelog/i.test(p.path)) {
      optionalLinks.push(line);
    } else {
      coreLinks.push(line);
    }
  }

  // Also inspect homepage internal links if only 1 page was crawled
  if (coreLinks.length <= 1) {
    for (const link of home.parsed.links.filter((l) => l.internal).slice(0, 8)) {
      if (seen.has(link.url)) continue;
      if (/\.(png|jpe?g|gif|webp|svg|ico|pdf|zip|css|js|xml|txt)$/i.test(link.url)) continue;
      seen.add(link.url);
      const label = link.text || link.url.replace(origin, '') || 'Page';
      const line = `- [${label}](${link.url}): Site section on ${brandName}.`;
      if (/privacy|terms|legal|cookie|changelog/i.test(link.url)) {
        optionalLinks.push(line);
      } else {
        coreLinks.push(line);
      }
    }
  }

  if (coreLinks.length === 0) {
    coreLinks.push(`- [${brandName} Home](${origin}/): Official homepage and product overview.`);
  }

  const lines = [
    `# ${brandName}`,
    '',
    `> ${summary.replace(/\s+/g, ' ').trim()}`,
    '',
    `This file follows the llmstxt.org standard to help AI assistants accurately retrieve and cite ${brandName}.`,
    '',
    '## Key Pages',
    ...coreLinks,
    '',
    '## Machine-Readable Resources',
    `- [Full Markdown Context](${origin}/llms-full.txt): Consolidated site overview for single-fetch retrieval.`,
    `- [XML Sitemap](${origin}/sitemap.xml): Canonical URL index for search and AI crawlers.`,
  ];

  if (optionalLinks.length > 0) {
    lines.push('', '## Optional', ...optionalLinks);
  }

  const content = lines.join('\n') + '\n';
  const check = validateLlmsTxt(content);
  if (!check.valid) {
    throw new Error(`Generated llms.txt failed spec validation: ${check.issues.join('; ')}`);
  }
  return content;
}

function buildLlmsFullTxt(siteData, brandName, summary) {
  const lines = [
    `# ${brandName} — Full Context Reference`,
    '',
    `> ${summary}`,
    '',
    `Canonical Origin: ${siteData.origin}`,
    `Generated By: CiteReady Auto-Fix Engine`,
    '',
    '---',
    '',
  ];

  for (const page of siteData.pages) {
    const p = page.parsed;
    lines.push(`## ${p.title || page.path || 'Page'}`);
    lines.push(`URL: ${page.url}`);
    if (p.metaMap.description) {
      lines.push(`Summary: ${p.metaMap.description}`);
    }
    const hList = p.headings.slice(0, 10).map((h) => `${'#'.repeat(Math.min(6, h.level + 2))} ${h.text}`);
    if (hList.length > 0) {
      lines.push('', 'Key Sections:', ...hList);
    }
    if (p.firstParagraph) {
      lines.push('', 'Overview:', p.firstParagraph);
    }
    if (p.faqPairs.length > 0) {
      lines.push('', 'Frequently Asked Questions:');
      for (const qa of p.faqPairs.slice(0, 10)) {
        lines.push(`- **Q: ${qa.question}**`, `  A: ${qa.answer}`);
      }
    }
    lines.push('', '---', '');
  }

  return lines.join('\n');
}

function buildRobotsTxt(siteData) {
  const origin = siteData.origin;
  const parsed = parseRobotsTxt(siteData.robotsTxt.text);
  const aiManagedAgents = new Set([
    'oai-searchbot',
    'chatgpt-user',
    'perplexitybot',
    'claudebot',
    'gptbot',
    'anthropic-ai',
    'google-extended',
  ]);

  const preservedBlocks = [];
  for (const group of parsed.groups) {
    const remainingAgents = group.agents.filter((a) => !aiManagedAgents.has(a));
    if (remainingAgents.length === 0) continue;

    // Filter out accidental blanket Disallow: / on User-agent: *
    const cleanedRules = group.rules.filter((r) => {
      if (remainingAgents.includes('*') && r.type === 'disallow' && r.path === '/') {
        return false;
      }
      return true;
    });

    const lines = remainingAgents.map((a) => `User-agent: ${a}`);
    if (cleanedRules.length === 0) {
      lines.push('Allow: /');
    } else {
      for (const r of cleanedRules) {
        const key = r.type === 'allow' ? 'Allow' : 'Disallow';
        lines.push(`${key}: ${r.path}`);
      }
    }
    preservedBlocks.push(lines.join('\n'));
  }

  if (preservedBlocks.length === 0) {
    preservedBlocks.push(['User-agent: *', 'Allow: /'].join('\n'));
  }

  const aiSearchSection = [
    '# AI Search & Citation Crawlers (Recommended: Allow for ChatGPT, Perplexity & Claude citations)',
    'User-agent: OAI-SearchBot',
    'Allow: /',
    '',
    'User-agent: ChatGPT-User',
    'Allow: /',
    '',
    'User-agent: PerplexityBot',
    'Allow: /',
    '',
    'User-agent: ClaudeBot',
    'Allow: /',
    '',
    '# Optional: AI Model Training Crawlers (Switch Allow: / to Disallow: / if you want to opt out of training)',
    'User-agent: GPTBot',
    'Allow: /',
    '',
    'User-agent: Google-Extended',
    'Allow: /',
  ].join('\n');

  const sitemaps = parsed.sitemaps.length > 0 ? parsed.sitemaps : [`${origin}/sitemap.xml`];
  const sitemapLines = [...new Set(sitemaps)].map((s) => `Sitemap: ${s}`).join('\n');

  return [
    '# Generated by CiteReady (https://citeready.eiran.tech)',
    '',
    preservedBlocks.join('\n\n'),
    '',
    aiSearchSection,
    '',
    sitemapLines,
    '',
  ].join('\n');
}

function buildJsonLdSnippets(siteData, brandName, summary) {
  const home = siteData.pages[0].parsed;
  const origin = siteData.origin;
  const ogImg = home.metaMap['og:image']
    ? new URL(home.metaMap['og:image'], origin).toString()
    : `${origin}/og-image.png`;

  const orgSchema = {
    '@context': 'https://schema.org',
    '@type': 'Organization',
    name: brandName,
    url: origin,
    description: summary,
    logo: ogImg,
  };

  const websiteSchema = {
    '@context': 'https://schema.org',
    '@type': 'WebSite',
    name: brandName,
    url: origin,
    description: summary,
  };

  const productSchema = {
    '@context': 'https://schema.org',
    '@type': 'SoftwareApplication',
    name: brandName,
    applicationCategory: 'BusinessApplication',
    operatingSystem: 'Web',
    url: origin,
    description: summary,
  };

  const faqs =
    home.faqPairs.length > 0
      ? home.faqPairs.slice(0, 8)
      : [
          {
            question: `What does ${brandName} do?`,
            answer: summary,
          },
          {
            question: `Where can I learn more about ${brandName}?`,
            answer: `Visit ${origin} for product overview, documentation, and pricing.`,
          },
        ];

  const faqSchema = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: faqs.map((item) => ({
      '@type': 'Question',
      name: item.question,
      acceptedAnswer: {
        '@type': 'Answer',
        text: item.answer,
      },
    })),
  };

  return [
    '<!-- Drop inside <head> of your site -->',
    safeJsonLdScript(orgSchema),
    safeJsonLdScript(websiteSchema),
    safeJsonLdScript(productSchema),
    safeJsonLdScript(faqSchema),
  ].join('\n\n') + '\n';
}

function buildHeadMetaPatch(siteData, brandName, summary) {
  const home = siteData.pages[0].parsed;
  const origin = siteData.origin;
  const title = home.title && home.title.length >= 20 ? home.title : `${brandName} — ${summary.slice(0, 48)}`;
  const desc = summary.slice(0, 160);
  const canonical = home.canonical || siteData.targetUrl || `${origin}/`;
  const ogImage = home.metaMap['og:image']
    ? new URL(home.metaMap['og:image'], origin).toString()
    : `${origin}/og-image.png`;

  return [
    '<!-- Drop inside <head> -->',
    `<title>${escapeHtml(title)}</title>`,
    `<meta name="description" content="${escapeHtml(desc)}">`,
    `<link rel="canonical" href="${escapeHtml(canonical)}">`,
    `<meta name="robots" content="index, follow">`,
    '',
    '<!-- Open Graph -->',
    `<meta property="og:type" content="website">`,
    `<meta property="og:site_name" content="${escapeHtml(brandName)}">`,
    `<meta property="og:title" content="${escapeHtml(title)}">`,
    `<meta property="og:description" content="${escapeHtml(desc)}">`,
    `<meta property="og:url" content="${escapeHtml(canonical)}">`,
    `<meta property="og:image" content="${escapeHtml(ogImage)}">`,
    '',
    '<!-- Twitter / X -->',
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${escapeHtml(title)}">`,
    `<meta name="twitter:description" content="${escapeHtml(desc)}">`,
    `<meta name="twitter:image" content="${escapeHtml(ogImage)}">`,
    '',
  ].join('\n');
}

function buildNextJsMetadata(siteData, brandName, summary) {
  const home = siteData.pages[0].parsed;
  const origin = siteData.origin;
  const title = home.title && home.title.length >= 20 ? home.title : `${brandName} — Official Site`;
  const desc = summary.slice(0, 160);
  const ogImage = home.metaMap['og:image']
    ? new URL(home.metaMap['og:image'], origin).toString()
    : `${origin}/og-image.png`;

  return `import type { Metadata } from 'next';

export const metadata: Metadata = {
  metadataBase: new URL(${JSON.stringify(origin)}),
  title: ${JSON.stringify(title)},
  description: ${JSON.stringify(desc)},
  alternates: {
    canonical: '/',
  },
  robots: {
    index: true,
    follow: true,
  },
  openGraph: {
    type: 'website',
    siteName: ${JSON.stringify(brandName)},
    title: ${JSON.stringify(title)},
    description: ${JSON.stringify(desc)},
    url: ${JSON.stringify(siteData.targetUrl || origin)},
    images: [{ url: ${JSON.stringify(ogImage)}, width: 1200, height: 630 }],
  },
  twitter: {
    card: 'summary_large_image',
    title: ${JSON.stringify(title)},
    description: ${JSON.stringify(desc)},
    images: [${JSON.stringify(ogImage)}],
  },
};
`;
}

export function generateFixes(siteData, auditResult) {
  const home = siteData.pages[0].parsed;
  const brandName = inferBrandName(home, siteData.origin);
  const summary = inferSummary(home, brandName);

  return {
    'llms.txt': buildLlmsTxt(siteData, brandName, summary),
    'llms-full.txt': buildLlmsFullTxt(siteData, brandName, summary),
    'robots.txt': buildRobotsTxt(siteData),
    'jsonld-snippets.html': buildJsonLdSnippets(siteData, brandName, summary),
    'head-meta-patch.html': buildHeadMetaPatch(siteData, brandName, summary),
    'nextjs-metadata.ts': buildNextJsMetadata(siteData, brandName, summary),
  };
}
