/**
 * Generates site/sample-report.html by running the real CiteReady engine
 * against a realistic broken indie SaaS demo fixture ("InvoiceSpark Demo").
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseHtml } from '../src/html-parser.mjs';
import { auditSite } from '../src/auditor.mjs';
import { generateFixes } from '../src/fix-generator.mjs';
import { renderHtmlReport } from '../src/report-html.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

const DEMO_HTML = `<!doctype html>
<html>
<head>
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>InvoiceSpark — Simple Client Invoicing</title>
  <meta name="description" content="Create client invoices quickly without complex accounting tools.">
  <meta property="og:title" content="InvoiceSpark">
</head>
<body>
  <header><nav><a href="/pricing">Pricing</a> <a href="/docs">Docs</a></nav></header>
  <h1>Client Invoicing Without Monthly Accounting Bloat</h1>
  <p>InvoiceSpark helps solo freelancers generate PDF invoices and track overdue client payments in minutes.</p>
  <img src="/dashboard.png">
</body>
</html>`;

const DEMO_ROBOTS = `User-agent: *
Allow: /

# Accidental legacy block left over from scraper blocking
User-agent: OAI-SearchBot
Disallow: /

User-agent: PerplexityBot
Disallow: /
`;

async function main() {
  const origin = 'https://invoicespark-demo.example.com';
  const siteData = {
    mode: 'sample-demo',
    targetUrl: `${origin}/`,
    origin,
    homeHeaders: { 'content-type': 'text/html' },
    homeOk: true,
    homeStatus: 200,
    homeError: null,
    robotsTxt: { ok: true, status: 200, text: DEMO_ROBOTS },
    llmsTxt: { ok: false, status: 404, text: '' },
    llmsFullTxt: { ok: false, status: 404, text: '' },
    sitemapXml: { ok: false, status: 404, text: '' },
    ogImageCheck: { checked: false, ok: false, status: 0, error: 'Missing og:image tag' },
    pages: [
      {
        url: `${origin}/`,
        path: '/',
        status: 200,
        ok: true,
        error: null,
        headers: {},
        parsed: parseHtml(DEMO_HTML, `${origin}/`),
      },
    ],
  };

  const auditResult = auditSite(siteData);
  const fixes = generateFixes(siteData, auditResult);
  const html = renderHtmlReport(auditResult, fixes, {
    brand: 'CiteReady',
    demoNotice:
      'SAMPLE DEMO REPORT: Generated by CiteReady v1.0.0 against a synthetic "InvoiceSpark" broken SaaS fixture to illustrate exact report structure and auto-generated fix files.',
  });

  const outPath = path.join(ROOT, 'site', 'sample-report.html');
  await fs.writeFile(outPath, html, 'utf8');
  console.log(`Sample report written to ${outPath} (demo fixture score: ${auditResult.score}/100)`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
